#!/bin/sh
# homebrew-formula.sh prints the Homebrew formula for one Chorus release.
#
# Usage: scripts/homebrew-formula.sh VERSION CHECKSUMS_FILE
#
# VERSION is the release version without the leading "v" (for example 0.6.0).
# CHECKSUMS_FILE is the release's checksums.txt, as written by
# `make build-release-assets` and published with the GitHub release. The
# formula downloads the release archive for the user's OS and CPU from GitHub
# and checks it against the SHA-256 recorded here. `make release` writes the
# output to Formula/chorus.rb in github.com/goadesign/homebrew-tap.
#
# The script fails, printing nothing, when an archive is missing from
# CHECKSUMS_FILE.
set -eu

if [ "$#" -ne 2 ]; then
	echo "usage: $0 VERSION CHECKSUMS_FILE" >&2
	exit 2
fi
version="$1"
checksums="$2"

# sum prints the SHA-256 of the archive for one OS and CPU.
sum() {
	archive="chorus_${version}_$1_$2.tar.gz"
	value="$(awk -v name="$archive" '$2 == name { print $1 }' "$checksums")"
	if [ -z "$value" ]; then
		echo "error: $archive is not listed in $checksums" >&2
		exit 1
	fi
	echo "$value"
}

darwin_arm64="$(sum darwin arm64)"
darwin_amd64="$(sum darwin amd64)"
linux_arm64="$(sum linux arm64)"
linux_amd64="$(sum linux amd64)"
base="https://github.com/goadesign/chorus/releases/download/v${version}"

cat <<EOF
# Formula/chorus.rb is generated by scripts/homebrew-formula.sh in
# github.com/goadesign/chorus during \`make release\`. Do not edit it by hand.
class Chorus < Formula
  desc "Real-time channels and direct messages for coordinating coding agents"
  homepage "https://github.com/goadesign/chorus"
  license "MIT"

  depends_on "redis"

  on_macos do
    on_arm do
      url "${base}/chorus_${version}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/chorus_${version}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/chorus_${version}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/chorus_${version}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "chorus"
  end

  def caveats
    <<~EOS
      To register Chorus with your coding agents and start it in the background, run:
        chorus setup -global && chorus up
      The live dashboard is then at http://localhost:9440/
    EOS
  end

  test do
    assert_match "chorus v#{version}", shell_output("#{bin}/chorus version")
  end
end
EOF
